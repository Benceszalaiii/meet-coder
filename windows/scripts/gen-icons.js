// One-off generator: maps the SF Symbols used by the macOS app to Lucide (ISC) shapes. Output: src/renderer/icons.js
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'node_modules', 'lucide-static', 'icons');
const parts = n => {
  const svg = fs.readFileSync(path.join(dir, n + '.svg'), 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '');
  return inner.match(/<[a-z]+[^>]*\/>/g).map(s => s.trim());
};
const all = n => parts(n).join('');
// filled shape with the glyph knocked out (like SF ".fill" symbols)
const knock = (n, id) => {
  const [outer, ...rest] = parts(n);
  return `<mask id="${id}"><rect width="24" height="24" fill="#fff"/><g stroke="#000" fill="none" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${rest.join('')}</g></mask>` +
         `<g mask="url(#${id})">${outer.replace('/>', ' fill="currentColor" stroke="none"/>')}</g>`;
};
const I = {};
const fill = (n) => ({ fill: true, body: all(n) });
const stroke = (n, sw) => ({ fill: false, sw, body: all(n) });
I['play.fill'] = fill('play');
I['stop.fill'] = fill('square');
I['sparkles.rectangle.stack.fill'] = { fill: true, body: all('sparkles') };
I['macwindow'] = stroke('app-window');
I['person.fill'] = fill('user');
I['folder.fill'] = fill('folder');
I['questionmark.folder'] = { fill: false, body: parts('folder')[0] + '<path d="M10.2 11.6a1.9 1.9 0 1 1 2.6 1.8c-.5.2-.8.6-.8 1.1"/><path d="M12 17h.01"/>' };
const drive = (badge) => ({ fill: false, body: `<g transform="translate(-1.2 -2.2) scale(.82)">${all('hard-drive')}</g>${badge}` });
I['externaldrive.fill.badge.plus'] = drive('<path d="M18 14v7M14.5 17.5h7"/>');
I['externaldrive.badge.xmark'] = drive('<path d="M15.5 15.5l5 5M20.5 15.5l-5 5"/>');
I['externaldrive.badge.questionmark'] = drive('<path d="M15.6 16.3a2 2 0 1 1 2.8 1.8c-.4.2-.4.5-.4.9"/><path d="M18 21h.01"/>');
I['externaldrive.fill'] = fill('hard-drive');
I['arrow.up.left.and.arrow.down.right'] = stroke('maximize-2');
I['pip'] = stroke('picture-in-picture-2');
I['gearshape.fill'] = stroke('settings');
I['dot.radiowaves.left.and.right'] = stroke('radio');
I['rectangle.dashed.badge.record'] = { fill: false, body: all('square-dashed') + '<circle cx="12" cy="12" r="3" fill="currentColor"/>' };
I['hammer.fill'] = stroke('hammer');
I['moon.zzz.fill'] = fill('moon');
I['clock'] = stroke('clock');
I['arrow.up.circle.fill'] = { fill: false, body: knock('circle-arrow-up', 'k-up') };
I['list.bullet.rectangle.fill'] = stroke('layout-list');
I['wand.and.stars'] = stroke('wand-sparkles');
I['sparkle'] = fill('sparkle');
I['chevron.down'] = { fill: false, sw: 3, body: all('chevron-down') };
I['server.rack'] = stroke('server');
I['globe'] = stroke('globe');
I['note.text'] = stroke('notebook-text');
I['arrow.up.forward.square'] = stroke('square-arrow-out-up-right');
I['exclamationmark.triangle.fill'] = { fill: false, body: knock('triangle-alert', 'k-warn') };
I['checkmark.circle.fill'] = { fill: false, body: knock('circle-check', 'k-ok') };
I['checkmark.circle'] = stroke('circle-check');
I['pause.circle.fill'] = { fill: false, body: knock('circle-pause', 'k-pause') };
I['arrow.uturn.backward'] = stroke('undo-2');
I['arrow.down.doc.fill'] = stroke('file-down');
I['arrow.right'] = stroke('arrow-right', 2.4);
I['arrow.up'] = stroke('arrow-up', 2.4);
I['checkmark'] = stroke('check', 2.6);
const out = '// Generated by scripts/gen-icons.js — SF Symbol names mapped to Lucide shapes (ISC licence).\n' +
  'export const ICONS = ' + JSON.stringify(I, null, 1) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', 'renderer', 'icons.js'), out);
console.log(Object.keys(I).length, 'icons');
